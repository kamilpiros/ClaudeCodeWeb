// Generates functions/_lib/migrations.generated.ts from migrations/*.sql so
// the Worker can self-migrate the database at runtime (no wrangler needed).
// Runs automatically as part of `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS_DIR = join(ROOT, "migrations");
const OUT = join(ROOT, "functions", "_lib", "migrations.generated.ts");

const files = readdirSync(MIGRATIONS_DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((name) => {
  const sql = readFileSync(join(MIGRATIONS_DIR, name), "utf8")
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  return `  {\n    name: ${JSON.stringify(name)},\n    sql: \`${sql}\`,\n  },`;
});

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n// Source of truth: /migrations/*.sql\n\nexport interface Migration {\n  name: string;\n  sql: string;\n}\n\nexport const MIGRATIONS: Migration[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`wrote ${OUT} (${files.length} migrations)`);
